from datetime import datetime
from typing import Any, Dict, List, Optional, Tuple

from pydantic import BaseModel, Field


class JobRunRef(BaseModel):
    id: str
    status: str


class JobInfo(BaseModel):
    id: str
    title: str
    description: str
    workflow: str = Field(
        ..., description="GitHub Actions workflow running it on a schedule"
    )
    schedule: str
    uses_model: bool
    default_model: Optional[str] = Field(
        None, description="Model reference used when a run names none (jobs role)"
    )
    has_draft: bool = Field(
        ..., description="Runs stop at a draft to review, published separately"
    )
    configured: bool
    missing_env: List[str] = Field(
        default_factory=list, description="Server env vars still to set"
    )
    options_schema: Dict[str, Any] = Field(
        ..., description="JSON schema of the options POST /jobs/{id}/run accepts"
    )
    latest_run: Optional[JobRunRef] = None


class JobsResponse(BaseModel):
    jobs: List[JobInfo]


class JobRunRequest(BaseModel):
    options: Dict[str, Any] = Field(
        default_factory=dict, description="Validated against the job's options_schema"
    )
    model_ref: Optional[str] = Field(
        None,
        description='Model reference, e.g. "claude:claude-sonnet-5" (jobs using a '
        "model only; default: the jobs role default)",
    )


class JobResultOut(BaseModel):
    dry_run: bool
    url: Optional[str] = None
    metrics: List[Tuple[str, Any]] = Field(
        default_factory=list, description="(label, value) pairs, in display order"
    )
    errors: List[str] = Field(default_factory=list, description="Non-fatal errors")


class JobProgress(BaseModel):
    done: int
    total: int
    label: str


class DraftPair(BaseModel):
    id: Optional[str] = None
    question: str
    answer: str
    category: Optional[str] = None
    repo: Optional[str] = None
    confidence: Optional[float] = None
    grounding: Optional[float] = None


class DraftPreview(BaseModel):
    repo_id: Optional[str] = Field(
        None, description="Hugging Face repo it publishes to"
    )
    kept: int = Field(..., description="Pairs carried over from unchanged sources")
    new: List[DraftPair] = Field(..., description="Pairs generated by this run")
    review: List[DraftPair] = Field(
        ..., description="Held out: answer far from its source (off by default)"
    )


class JobRunOut(BaseModel):
    id: str
    job: str
    status: str = Field(
        ..., description="running, succeeded, failed, published or interrupted"
    )
    options: Dict[str, Any] = Field(default_factory=dict)
    model_ref: Optional[str] = None
    started_at: datetime
    finished_at: Optional[datetime] = None
    progress: Optional[JobProgress] = None
    result: Optional[JobResultOut] = None
    error: Optional[str] = None
    has_draft: bool = False
    preview: Optional[DraftPreview] = None
    published_url: Optional[str] = None
    published_at: Optional[datetime] = None


class PublishRequest(BaseModel):
    exclude: List[str] = Field(
        default_factory=list, description="Ids of new pairs to leave out"
    )
    promote: List[str] = Field(
        default_factory=list, description="Ids of review pairs to include"
    )
